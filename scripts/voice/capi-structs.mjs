// Writes app/voice/capi-structs.ts: the struct layouts Ember's koffi binding of sherpa-onnx's C API needs
// (app/voice/capi.ts), taken from the release's own c-api.h so they match it field for field. Run it again whenever
// sherpa-onnx's version changes (scripts/voice/fetch-capi.mjs fetches the release with its header).
// usage: node scripts/voice/capi-structs.mjs <path to sherpa-onnx/c-api/c-api.h> <version>
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [header, version] = process.argv.slice(2);
if (!header || !version) { console.error("usage: node scripts/voice/capi-structs.mjs <c-api.h> <version>"); process.exit(1); }
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const src = readFileSync(header, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "");
const structs = new Map();
for (const m of src.matchAll(/typedef\s+struct\s+\w+\s*\{([\s\S]*?)\}\s*(\w+)\s*;/g)) structs.set(m[2], m[1]);

/** The structs the binding passes or reads; everything they contain comes with them, innermost first. */
const ROOTS = ["SherpaOnnxKeywordSpotterConfig", "SherpaOnnxVadModelConfig", "SherpaOnnxOfflineRecognizerConfig", "SherpaOnnxOfflineTtsConfig", "SherpaOnnxSpeechSegment", "SherpaOnnxGeneratedAudio"];
const order = [];
const koffiType = c => {
  const t = c.replace(/\bconst\b/g, "").replace(/\s+/g, " ").trim();
  if (/^char \*$/.test(t)) return "const char *";
  if (/\*/.test(t)) return t.startsWith("float") ? "float *" : "void *";
  if (t === "int32_t" || t === "float") return t;
  if (structs.has(t)) return t;
  throw new Error(`unknown field type "${c}"`);
};
function visit(name) {
  if (order.some(s => s.name === name)) return;
  const body = structs.get(name);
  if (!body) throw new Error(`no struct ${name} in ${header}`);
  const fields = body.split(";").map(f => f.trim()).filter(Boolean).map(f => {
    const m = /^(.*?[\s*])(\w+)$/.exec(f.replace(/\s+/g, " "));
    if (!m) throw new Error(`can't read the field "${f}" of ${name}`);
    return [m[2], koffiType(m[1])];
  });
  for (const [, t] of fields) if (structs.has(t)) visit(t);
  order.push({ name, fields });
}
ROOTS.forEach(visit);

const out = `/**
 * The struct layouts of sherpa-onnx ${version}'s C API that app/voice/capi.ts binds with koffi, field for field as its
 * c-api.h declares them (koffi lays them out with the C rules). Generated by scripts/voice/capi-structs.mjs: change
 * sherpa-onnx's version, then run it again, never edit this by hand.
 */

/** The sherpa-onnx release these layouts are from. */
export const CAPI_VERSION = ${JSON.stringify(version)};

/** Each struct's fields in order, as [name, koffi type]; a struct field names another struct listed before it. */
export const CAPI_STRUCTS: readonly { name: string; fields: readonly (readonly [string, string])[] }[] = [
${order.map(s => `  { name: ${JSON.stringify(s.name)}, fields: [${s.fields.map(([n, t]) => `[${JSON.stringify(n)}, ${JSON.stringify(t)}]`).join(", ")}] },`).join("\n")}
];
`;
writeFileSync(path.join(root, "app/voice/capi-structs.ts"), out);
console.log(`wrote ${order.length} structs`);
